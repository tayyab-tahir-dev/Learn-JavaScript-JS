// THE CONST KEYWORD IS USED TO DECLARE VARIABLES WITH BLOCK SCOPE, BUT ONCE A VALUE IS ASSIGNED TO A CONST VARIABLE, IT CANNOT BBE REASSIGNED.
// CONST VARIBLES ARE IMMUTABLE.

